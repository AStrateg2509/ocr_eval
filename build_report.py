# -------------------------- helpers -----------------------------------------

def set_run_font(run, size=14, bold=False, italic=False, name="Times New Roman"):
    run.font.name = name
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    for attr in ("ascii", "hAnsi", "eastAsia", "cs"):
        rFonts.set(qn(f"w:{attr}"), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic


def add_para(doc, text="", *, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
             bold=False, italic=False, size=14, indent_first=True,
             space_after=0, line_spacing=1.5, keep_with_next=False):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = line_spacing
    pf.space_before = Pt(0)
    pf.space_after = Pt(space_after)
    if indent_first and align != WD_ALIGN_PARAGRAPH.CENTER:
        pf.first_line_indent = Cm(1.25)
    if keep_with_next:
        pf.keep_with_next = True
    if text:
        run = p.add_run(text)
        set_run_font(run, size=size, bold=bold, italic=italic)
    return p


def add_heading(doc, text, level=1):
    """Заголовки в стиле отчёта: ВВЕДЕНИЕ/ЗАКЛЮЧЕНИЕ — center bold,
    1./1.1./1.1.1 — left bold, без отступа первой строки."""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_before = Pt(12)
    pf.space_after = Pt(6)
    pf.keep_with_next = True
    if level == 0:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(text.upper())
        set_run_font(run, size=14, bold=True)
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        pf.first_line_indent = Cm(1.25)
        run = p.add_run(text)
        set_run_font(run, size=14, bold=True)
    # outline level for TOC
    pPr = p._element.get_or_add_pPr()
    outl = OxmlElement("w:outlineLvl")
    outl.set(qn("w:val"), str(min(level, 5)))
    pPr.append(outl)
    return p


def add_pagebreak(doc):
    p = doc.add_paragraph()
    run = p.add_run()
    br = OxmlElement("w:br")
    br.set(qn("w:type"), "page")
    run._element.append(br)


def set_cell_borders(cell):
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for side in ("top", "left", "bottom", "right"):
        b = OxmlElement(f"w:{side}")
        b.set(qn("w:val"), "single")
        b.set(qn("w:sz"), "4")
        b.set(qn("w:color"), "000000")
        tcBorders.append(b)
    # tcBorders в OOXML должны идти перед shd / tcMar / vAlign / hideMark.
    # Ищем первый «мешающий» дочерний элемент и вставляем перед ним.
    insert_before = None
    for child in tcPr:
        tag = child.tag.split("}")[-1]
        if tag in ("shd", "noWrap", "tcMar", "textDirection",
                  "tcFitText", "vAlign", "hideMark", "headers"):
            insert_before = child
            break
    if insert_before is not None:
        tcPr.insert(list(tcPr).index(insert_before), tcBorders)
    else:
        tcPr.append(tcBorders)


def add_table(doc, headers, rows, col_widths_cm=None, header_bold=True):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False

    if col_widths_cm:
        for i, w in enumerate(col_widths_cm):
            for row in table.rows:
                row.cells[i].width = Cm(w)

    # header
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        cell.paragraphs[0].paragraph_format.line_spacing = 1.15
        cell.paragraphs[0].paragraph_format.space_before = Pt(2)
        cell.paragraphs[0].paragraph_format.space_after = Pt(2)
        run = cell.paragraphs[0].add_run(h)
        set_run_font(run, size=12, bold=header_bold)
        set_cell_borders(cell)

    # rows
    for r_idx, r in enumerate(rows):
        for c_idx, val in enumerate(r):
            cell = table.rows[1 + r_idx].cells[c_idx]
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            par = cell.paragraphs[0]
            par.paragraph_format.line_spacing = 1.15
            par.paragraph_format.space_before = Pt(2)
            par.paragraph_format.space_after = Pt(2)
            par.alignment = WD_ALIGN_PARAGRAPH.CENTER if c_idx > 0 else WD_ALIGN_PARAGRAPH.LEFT
            run = par.add_run(str(val))
            set_run_font(run, size=12)
            set_cell_borders(cell)
    return table


def add_caption(doc, text, *, kind="Таблица"):
    """'Таблица 1 — название' — выравнивание по правому краю для таблиц,
    по центру — для рисунков (по ГОСТ для НИР)."""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.0
    pf.space_before = Pt(2)
    pf.space_after = Pt(6)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf.first_line_indent = Cm(0)
    run = p.add_run(text)
    set_run_font(run, size=12, italic=False, bold=False)
    return p


def add_bullet_list(doc, items, *, ordered=False):
    """Простые маркированные / нумерованные списки."""
    for i, t in enumerate(items, 1):
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.line_spacing = 1.5
        pf.left_indent = Cm(1.25)
        pf.first_line_indent = Cm(0)
        pf.space_after = Pt(0)
        prefix = f"{i}. " if ordered else "— "
        run = p.add_run(prefix + t)
        set_run_font(run, size=14)


